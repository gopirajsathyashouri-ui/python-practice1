# alma better problem Identify Data Types in a Personal Information Form

name = "John Doe"  
age = 30  # Age (integer)
salary = 75000.50  # Salary (float)
experience = True  # Experience (boolean)
hobbies = ["reading", "traveling", "swimming"]  # Hobbies (list)
skills = ("Python", "Data Analysis", "Machine Learning")  # Skills (tuple)
address = {
    "street": "1234 Elm St",
    "city": "Springfield",
    "state": "IL",
    "zip": "62704"
}  

print(type(name))
print(type(age))
print(type(salary))
print(type(experience))
print(type(hobbies))
print(type(skills))
print(type(address))
